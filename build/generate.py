#!/usr/bin/env python3
"""
generate.py — emit the nginx config + startup script for the all-in-one image.

Single source of truth = apps/_ports.py (ports) + the SHIP_READY list below
(mirrors launch.py / the umbrella UI). Run at image-build time so nginx and the
launcher always agree with the rest of the repo.

Routing model (one exposed port, default 8080):
    /                       → the built umbrella UI (static SPA)
    /a/<app>/               → reverse-proxied to the app on 127.0.0.1:<port>
    /healthz                → 200 (Code Engine readiness)

Each app's UI uses absolute paths (fetch('/ask'), '/session/…', '/static/…').
Under a path prefix those would hit the origin root and 404, so for every app
location nginx injects — into the HTML <head> — a <base href> plus a tiny
window.fetch shim that prepends the app's prefix to same-origin absolute URLs.
This is generic and needs no change to any app.

Usage:
    python generate.py --apps-dir /app/apps \
        --nginx /etc/nginx/conf.d/default.conf --start /app/run_all.sh
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

# The 21 ship-ready apps (dir names). Mirrors launch.py SHIP_READY and the
# umbrella UI's ship-ready set.
SHIP_READY = [
    "stock_alert", "server_monitor", "newsletter", "web_researcher", "travel_planner",
    "youtube_research", "arch_diagram", "hiking_research", "movie_recommender",
    "webpage_summarizer", "paper_scout", "wiki_dive", "ibm_cloud_advisor", "ibm_docs_qa",
    "recipe_composer", "city_beat", "ouroboros", "github_trending", "ai_labs_news",
    "find_a_doctor", "meetup_finder",
]

# travel_planner is served via uvicorn.run("main:app") and reads PORT from the
# env instead of a --port flag.
PORT_VIA_ENV = {"travel_planner"}


def _load_ports(apps_dir: str) -> dict:
    sys.path.insert(0, apps_dir)
    from _ports import APP_PORTS  # type: ignore
    return APP_PORTS


def _seg(app_dir: str) -> str:
    """URL path segment for an app — hyphenated, matching the UI's
    CE-name-derived path (cuga-apps-<seg>)."""
    return app_dir.replace("_", "-")


def _location_block(app_dir: str, port: int) -> str:
    seg = _seg(app_dir)
    prefix = f"/a/{seg}"
    # The injected <head> payload: <base href> + a fetch() shim that re-prefixes
    # same-origin absolute URLs. Single-quoted for nginx; uses only double quotes
    # inside so it never closes the nginx string.
    shim = (
        f'<base href="{prefix}/">'
        f'<script>(function(){{var P="{prefix}";var f=window.fetch;'
        f'window.fetch=function(u,o){{try{{if(typeof u==="string"&&u.charAt(0)==="/"'
        f'&&u.indexOf(P)!==0){{u=P+u;}}}}catch(e){{}}return f(u,o);}};}})();</script>'
        f'</head>'
    )
    return f"""\
    # ── {app_dir} ──
    location = {prefix} {{ return 301 {prefix}/; }}
    location {prefix}/ {{
        proxy_pass http://127.0.0.1:{port}/;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Accept-Encoding "";   # let sub_filter rewrite plaintext HTML
        proxy_read_timeout 600s;               # agent calls can take minutes
        proxy_send_timeout 600s;
        sub_filter_once on;
        sub_filter_types text/html;
        sub_filter '</head>' '{shim}';
        sub_filter '"/static/' '"{prefix}/static/';
    }}
"""


def gen_nginx(ports: dict) -> str:
    blocks = "\n".join(_location_block(a, ports[a]) for a in SHIP_READY if a in ports)
    return f"""\
# AUTO-GENERATED by build/generate.py — do not edit by hand.
server {{
    listen 8080;
    server_name _;
    client_max_body_size 2m;
    absolute_redirect off;

    # Code Engine readiness probe.
    location = /healthz {{ add_header Content-Type text/plain; return 200 "ok"; }}

    # Umbrella UI (static SPA).
    location / {{
        root /app/ui-dist;
        try_files $uri $uri/ /index.html;
    }}

    # Ship-ready apps, each reverse-proxied + path-prefixed.
{blocks}
}}
"""


def gen_start(ports: dict) -> str:
    lines = [
        "#!/usr/bin/env bash",
        "# AUTO-GENERATED by build/generate.py — do not edit by hand.",
        "# Starts every ship-ready app on 127.0.0.1:<port>, then execs nginx (PID 1).",
        "set -u",
        'cd /app/apps || exit 1',
        '# MCP-backed apps use the hosted Code Engine MCP servers by default.',
        'export CUGA_TARGET="${CUGA_TARGET:-ce}"',
        'export CUGA_IN_DOCKER=1',
        'log() { echo "[run_all] $*"; }',
        "",
    ]
    for app in SHIP_READY:
        if app not in ports:
            continue
        port = ports[app]
        lines.append(f'log "starting {app} on :{port}"')
        if app in PORT_VIA_ENV:
            lines.append(f'PORT={port} python -u {app}/main.py &')
        else:
            lines.append(f'python -u {app}/main.py --port {port} &')
        lines.append("")
    lines += [
        'log "all ship-ready apps launched; starting nginx on :8080"',
        "exec nginx -g 'daemon off;'",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apps-dir", default="/app/apps")
    ap.add_argument("--nginx", required=True)
    ap.add_argument("--start", required=True)
    args = ap.parse_args()

    ports = _load_ports(args.apps_dir)
    Path(args.nginx).write_text(gen_nginx(ports))
    Path(args.start).write_text(gen_start(ports))
    print(f"generate.py: wrote {args.nginx} and {args.start} "
          f"for {sum(1 for a in SHIP_READY if a in ports)} ship-ready apps")


if __name__ == "__main__":
    main()
